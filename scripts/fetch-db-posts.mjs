// Fetches published posts from Supabase blog_posts and writes
// src/data/dbBlogPosts.generated.ts. Runs in `prebuild` so the
// unified registry (md + JSON + DB) is available at build time.
//
// Failure policy: this script never fails the build. On network errors
// or missing env vars it writes an empty catalog and prints a warning —
// prerender simply falls back to md + JSON sources.

import { writeFileSync, mkdirSync, existsSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT_PATH = resolve(__dirname, "../src/data/dbBlogPosts.generated.ts");

function readEnv(name) {
  if (process.env[name]) return process.env[name];
  // Fallback to .env for local runs
  const envPath = resolve(__dirname, "../.env");
  if (!existsSync(envPath)) return undefined;
  const line = readFileSync(envPath, "utf8")
    .split("\n")
    .find((l) => l.startsWith(name + "="));
  if (!line) return undefined;
  return line.slice(name.length + 1).replace(/^["']|["']$/g, "");
}

const SUPABASE_URL = readEnv("VITE_SUPABASE_URL") || readEnv("SUPABASE_URL");
const SUPABASE_KEY =
  readEnv("VITE_SUPABASE_PUBLISHABLE_KEY") ||
  readEnv("SUPABASE_PUBLISHABLE_KEY") ||
  readEnv("SUPABASE_ANON_KEY");

function writeCatalog(rows, note) {
  mkdirSync(dirname(OUT_PATH), { recursive: true });
  const header = `// AUTO-GENERATED by scripts/fetch-db-posts.mjs — DO NOT EDIT.\n// ${note}\n// Regenerate with: bun run scripts/fetch-db-posts.mjs\n`;
  const body = `import type { BlogPost } from "./blogPosts";\n\nexport const dbBlogPosts: BlogPost[] = ${JSON.stringify(rows, null, 2)};\n`;
  writeFileSync(OUT_PATH, header + body, "utf8");
}

function toBlogPost(row) {
  // Content is jsonb: array of blocks with the same shape as parseContent output
  const rawContent = Array.isArray(row.content) ? row.content : [];
  const content = rawContent
    .filter((b) => b && typeof b === "object" && b.type)
    .map((b) => ({
      type: b.type,
      text: b.text || "",
      ...(b.level ? { level: b.level } : {}),
      ...(b.componentId ? { componentId: b.componentId } : {}),
      ...(b.headers ? { headers: b.headers } : {}),
      ...(b.rows ? { rows: b.rows } : {}),
    }));
  const updatedIso = row.updated_at ? String(row.updated_at).slice(0, 10) : undefined;
  const dateIso = row.date || (row.created_at ? String(row.created_at).slice(0, 10) : "");
  return {
    id: row.id || row.slug,
    slug: row.slug,
    title: row.title,
    description: row.description || "",
    image: row.image || "/placeholder.svg",
    date: dateIso,
    ...(updatedIso && updatedIso !== dateIso ? { updatedAt: updatedIso } : {}),
    tags: Array.isArray(row.tags) ? row.tags : [],
    content,
  };
}

async function main() {
  if (!SUPABASE_URL || !SUPABASE_KEY) {
    console.warn("[fetch-db-posts] missing SUPABASE env — writing empty catalog");
    writeCatalog([], "empty (missing SUPABASE env at build time)");
    return;
  }

  const endpoint = `${SUPABASE_URL.replace(/\/+$/, "")}/rest/v1/blog_posts?select=*&published=eq.true&order=date.desc`;
  try {
    const res = await fetch(endpoint, {
      headers: {
        apikey: SUPABASE_KEY,
        Authorization: `Bearer ${SUPABASE_KEY}`,
        Accept: "application/json",
      },
    });
    if (!res.ok) {
      const text = await res.text();
      console.warn(`[fetch-db-posts] HTTP ${res.status}: ${text.slice(0, 200)} — writing empty catalog`);
      writeCatalog([], `empty (HTTP ${res.status})`);
      return;
    }
    const rows = await res.json();
    const posts = rows
      .filter((r) => r && r.slug && r.title)
      .map(toBlogPost);
    writeCatalog(posts, `${posts.length} published post(s) fetched at ${new Date().toISOString()}`);
    console.log(`[fetch-db-posts] wrote ${posts.length} post(s) to src/data/dbBlogPosts.generated.ts`);
  } catch (err) {
    console.warn(`[fetch-db-posts] ${err?.message || err} — writing empty catalog`);
    writeCatalog([], `empty (error: ${err?.message || err})`);
  }
}

main();
