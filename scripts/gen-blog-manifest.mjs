import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "src/content/blog";
const files = readdirSync(dir).filter((f) => f.endsWith(".md")).sort();
const entries = files.map((f) => {
  const raw = readFileSync(join(dir, f), "utf8");
  const key = `/src/content/blog/${f}`;
  return `  ${JSON.stringify(key)}: ${JSON.stringify(raw)},`;
});
const out = `// AUTO-GENERATED by scripts/gen-blog-manifest.mjs — do not edit.
// Regenerate: node scripts/gen-blog-manifest.mjs
// Inlines all Markdown blog posts so non-Vite runtimes (Deno MCP bundle,
// prerender) can load them without import.meta.glob.
export const blogMdManifest: Record<string, string> = {
${entries.join("\n")}
};
`;
writeFileSync(join(dir, "_manifest.generated.ts"), out);
console.log(`Wrote ${files.length} md files to ${dir}/_manifest.generated.ts`);
