// Generates src/lib/mcp/posts.generated.ts: a lean, plain-text catalog of
// every blog post (md + legacy) for use inside the Supabase MCP edge function
// only. Keeps the mcp bundle small enough to deploy.
//
// Regenerate: node scripts/gen-mcp-posts.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { register } from "node:module";

// --- Load md posts (frontmatter + body) ---------------------------------
function parseFrontmatter(src) {
  const m = src.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?([\s\S]*)$/);
  if (!m) return { data: {}, body: src };
  const [, yaml, body] = m;
  const data = {};
  const lines = yaml.split(/\r?\n/);
  let key = null;
  const strip = (s) =>
    (s.startsWith('"') && s.endsWith('"')) || (s.startsWith("'") && s.endsWith("'"))
      ? s.slice(1, -1)
      : s;
  for (const raw of lines) {
    if (!raw.trim()) continue;
    const li = raw.match(/^\s*-\s+(.*)$/);
    if (li && key) {
      if (!Array.isArray(data[key])) data[key] = [];
      data[key].push(strip(li[1].trim()));
      continue;
    }
    const kv = raw.match(/^([A-Za-z_][A-Za-z0-9_]*)\s*:\s*(.*)$/);
    if (kv) {
      key = kv[1];
      const v = kv[2].trim();
      data[key] = v === "" ? [] : strip(v);
    }
  }
  return { data, body: body ?? "" };
}

const mdDir = "src/content/blog";
const mdPosts = readdirSync(mdDir)
  .filter((f) => f.endsWith(".md"))
  .map((f) => {
    const raw = readFileSync(join(mdDir, f), "utf8");
    const { data, body } = parseFrontmatter(raw);
    return {
      slug: data.slug,
      title: data.title,
      description: data.description || "",
      date: data.date || "",
      updatedAt: data.updatedAt || undefined,
      tags: Array.isArray(data.tags) ? data.tags : [],
      body,
    };
  });
const mdSlugs = new Set(mdPosts.map((p) => p.slug));

// --- Load legacy blogPosts.ts by stripping types and evaluating ---------
// Parse via tsx-like approach: use `bun` if available, else naive extract.
// Simpler: read as text and extract each post object via regex is fragile.
// Instead, execute it through tsx.
let legacyPosts = [];
try {
  const src = readFileSync("src/data/blogPosts.ts", "utf8");
  // Extract "export const blogPosts: BlogPost[] = [ ... ];" body via a naive scan
  // that stops at the matching bracket. Fall back to empty if it fails.
  const startIdx = src.indexOf("export const blogPosts");
  const eqIdx = src.indexOf("[", startIdx);
  let depth = 0;
  let endIdx = -1;
  for (let i = eqIdx; i < src.length; i++) {
    const c = src[i];
    if (c === "[") depth++;
    else if (c === "]") {
      depth--;
      if (depth === 0) {
        endIdx = i + 1;
        break;
      }
    }
  }
  if (endIdx > 0) {
    const literal = src.slice(eqIdx, endIdx);
    // Evaluate as JS. It contains TS-only bits inside object literals? No,
    // just plain object/array literals with strings.
    // eslint-disable-next-line no-new-func
    legacyPosts = new Function(`return ${literal}`)();
  }
} catch (e) {
  console.error("Failed to parse legacy blogPosts.ts:", e.message);
}

function stripHtml(html) {
  return String(html || "")
    .replace(/<br\s*\/?>/gi, "\n")
    .replace(/<\/p>/gi, "\n\n")
    .replace(/<\/li>/gi, "\n")
    .replace(/<li[^>]*>/gi, "- ")
    .replace(/<[^>]+>/g, "")
    .replace(/&nbsp;/g, " ")
    .replace(/&amp;/g, "&")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .replace(/[ \t]+\n/g, "\n")
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}

const legacyReduced = legacyPosts
  .filter((p) => p && p.slug && !mdSlugs.has(p.slug))
  .map((p) => {
    const body = (p.content || [])
      .map((b) => {
        if (!b) return "";
        if (b.type === "heading") return `${"#".repeat((b.level || 2) + 1)} ${stripHtml(b.text)}`;
        if (b.type === "quote") return `> ${stripHtml(b.text)}`;
        if (b.type === "component") return `_[interactive: ${b.componentId}]_`;
        return stripHtml(b.text);
      })
      .filter(Boolean)
      .join("\n\n");
    return {
      slug: p.slug,
      title: p.title,
      description: p.description || "",
      date: p.date || "",
      updatedAt: p.updatedAt || undefined,
      tags: Array.isArray(p.tags) ? p.tags : [],
      body,
    };
  });

const all = [...mdPosts, ...legacyReduced].sort((a, b) =>
  (b.date || "").localeCompare(a.date || "")
);

const out = `// AUTO-GENERATED by scripts/gen-mcp-posts.mjs — do not edit.
// Regenerate: node scripts/gen-mcp-posts.mjs
// Lean plain-text catalog of all blog posts (md + legacy) for the Supabase
// MCP edge function. Bodies are plain text so the bundle stays under Supabase's
// deploy size limit.
export interface McpPost {
  slug: string;
  title: string;
  description: string;
  date: string;
  updatedAt?: string;
  tags: string[];
  body: string;
}
export const mcpPosts: McpPost[] = ${JSON.stringify(all, null, 2)};
`;
writeFileSync("src/lib/mcp/posts.generated.ts", out);
console.log(`Wrote ${all.length} posts (${mdPosts.length} md + ${legacyReduced.length} legacy) → src/lib/mcp/posts.generated.ts`);
