// Generates src/lib/mcp/posts.generated.ts: a lean plain-text catalog of all
// blog posts (md + legacy) for the Supabase MCP edge function.
// Regenerate: bun run scripts/gen-mcp-posts.mjs
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { blogPosts as legacyPosts } from "../src/data/blogPosts.ts";
import { mdBlogPosts } from "../src/lib/loadMdBlogPosts.ts";

function stripHtml(html) {
  return String(html || "")
    .replace(/<br\s*\/?>/gi, "\n")
    .replace(/<\/p>/gi, "\n\n")
    .replace(/<\/li>/gi, "\n")
    .replace(/<li[^>]*>/gi, "- ")
    .replace(/<[^>]+>/g, "")
    .replace(/&nbsp;/g, " ").replace(/&amp;/g, "&").replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">").replace(/&quot;/g, '"').replace(/&#39;/g, "'")
    .replace(/[ \t]+\n/g, "\n").replace(/\n{3,}/g, "\n\n").trim();
}

function reduce(p) {
  const body = (p.content || [])
    .map((b) => {
      if (!b) return "";
      if (b.type === "markdown") return String(b.text || "");
      if (b.type === "heading") return `${"#".repeat((b.level || 2) + 1)} ${stripHtml(b.text)}`;
      if (b.type === "quote") return `> ${stripHtml(b.text)}`;
      if (b.type === "component") return `_[interactive: ${b.componentId}]_`;
      return stripHtml(b.text);
    })
    .filter(Boolean)
    .join("\n\n");
  return {
    slug: p.slug,
    title: p.title,
    description: p.description || "",
    date: p.date || "",
    updatedAt: p.updatedAt || undefined,
    tags: Array.isArray(p.tags) ? p.tags : [],
    body,
  };
}

const mdSlugs = new Set(mdBlogPosts.map((p) => p.slug));
const all = legacyPosts
  .map((p) => {
    const r = reduce(p);
    // Legacy HTML-based posts: keep metadata only. Full bodies bloat the mcp
    // bundle (Cyrillic \u-escapes triple the size) and are always reachable
    // at the public URL. Md-sourced posts keep their full markdown body.
    if (!mdSlugs.has(p.slug)) r.body = "";
    return r;
  })
  .sort((a, b) => (b.date || "").localeCompare(a.date || ""));


const out = `// AUTO-GENERATED by scripts/gen-mcp-posts.mjs — do not edit.
// Regenerate: bun run scripts/gen-mcp-posts.mjs
// Lean plain-text catalog of all blog posts for the Supabase MCP edge function.
// Bodies are stripped to plain text so the bundle stays under Supabase's deploy limit.
export interface McpPost {
  slug: string;
  title: string;
  description: string;
  date: string;
  updatedAt?: string;
  tags: string[];
  body: string;
}
export const mcpPosts: McpPost[] = ${JSON.stringify(all, null, 2)};
`;
writeFileSync("src/lib/mcp/posts.generated.ts", out);
console.log(`Wrote ${all.length} posts → src/lib/mcp/posts.generated.ts`);
