// BFI-10 (Rammstedt & John, 2007). 10 items, 5 Big Five dimensions.
// Each dimension has 2 items, one reverse-scored.
//   E (Extraversion): 1R, 6
//   A (Agreeableness): 2, 7R
//   C (Conscientiousness): 3R, 8
//   N (Neuroticism): 4R, 9
//   O (Openness): 5, 10R
// Reverse items: 1, 3, 4, 5, 7 ... actually per Rammstedt 2007: reverse = 1, 3, 4, 5, 7
// Updated table per published key: reverse = 1, 3, 4, 5, 7

const REV = new Set([1, 3, 4, 5, 7]);
const rev = (v: number) => 6 - v;

const dimScore = (answers: number[], a: number, b: number) => {
  const va = (REV.has(a) ? rev(answers[a - 1] ?? 3) : answers[a - 1] ?? 3);
  const vb = (REV.has(b) ? rev(answers[b - 1] ?? 3) : answers[b - 1] ?? 3);
  return va + vb; // 2..10
};

const band = (s: number) => (s <= 4 ? "низкий" : s <= 7 ? "средний" : "высокий");

