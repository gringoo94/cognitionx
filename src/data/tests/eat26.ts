// Eating Attitudes Test (EAT-26). Garner et al., 1982.
// 26 items. Items 1–25 scored: Always=3, Usually=2, Often=1, Sometimes/Rarely/Never=0.
// Item 26 reverse: Always/Usually/Often=0, Sometimes=1, Rarely=2, Never=3.
// Cutoff ≥20 → high risk, professional eval recommended.

