// Penn State Worry Questionnaire (PSWQ). Meyer, Miller, Metzger & Borkovec (1990).
// 16 items, 5-point scale (1–5). Items 1, 3, 8, 10, 11 are reverse-scored.
// Range 16–80. 16–39 low; 40–59 moderate; 60–80 high (GAD probable >65).

const SCALE: LikertOption[] = [
  { value: 1, label: "Совсем не про меня" },
  { value: 2, label: "Скорее не про меня" },
  { value: 3, label: "Иногда про меня" },
  { value: 4, label: "Часто про меня" },
  { value: 5, label: "Полностью про меня" },
];

const REVERSE = new Set([1, 3, 8, 10, 11]); // 1-based indices

const sum = (a: number[]) =>
  a.reduce((s, v, i) => {
    const val = v ?? 0;
    if (val === 0) return s;
    const adj = REVERSE.has(i + 1) ? 6 - val : val;
    return s + adj;
  }, 0);

